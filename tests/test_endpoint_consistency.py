"""Cross-endpoint consistency: the published JSON files must not contradict each other.

Why this exists: each endpoint is generated by a different script (`gen_site.py`, `gen_leaderboard`,
the drift/rescore pass, `gen_rubric.py`). If one of them is regenerated alone, the site can end up
publishing two numbers that disagree — and a reader has no way to tell which one is stale.
These checks only read the committed files, so an outsider can rerun them with no token and no clone.

Every assertion is a *relationship*, never a literal value: nothing here pins "16" or "58", because
pinning would make the test itself a place where a stale number hides.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
# 允许指向另一份 docs 副本，用于"喂坏数据必须报错"的反向验证（见 tests/selftest_endpoint_consistency.py）
DOCS = os.environ.get("LGD_DOCS") or os.path.join(REPO, "docs")


def jload(name):
    return json.load(open(os.path.join(DOCS, name), encoding="utf-8"))


results = []


def case(name, condition, detail):
    print(("PASS  " if condition else "FAIL  ") + name + " | " + detail)
    results.append(condition)
    return condition


lb = jload("leaderboard.json")
rp = jload("run-proof.json")
dc = jload("drift-check.json")
ls = jload("landscape.json")
rb = jload("rubric.json")

rows = lb["rows"]
summ = lb["summary"]
by_bucket = {}
for r in rows:
    by_bucket.setdefault(r["bucket"], []).append(r)

# 1. summary 必须能从 rows 重算出来
third = by_bucket.get("third-party", [])
lgd = by_bucket.get("lgd", [])
case("leaderboard: entry counts recompute from rows",
     summ["third_party_entries"] == len(third) and summ["lgd_entries"] == len(lgd),
     "summary=%d/%d rows=%d/%d" % (summ["third_party_entries"], summ["lgd_entries"], len(third), len(lgd)))
case("leaderboard: top scores recompute from rows",
     summ["third_party_top"] == max(r["score"] for r in third)
     and summ["lgd_top"] == max(r["score"] for r in lgd),
     "summary=%s/%s rows=%s/%s" % (summ["third_party_top"], summ["lgd_top"],
                                   max(r["score"] for r in third), max(r["score"] for r in lgd)))
case("leaderboard: gap equals top difference",
     summ["gap"] == summ["lgd_top"] - summ["third_party_top"],
     "gap=%s diff=%s" % (summ["gap"], summ["lgd_top"] - summ["third_party_top"]))

# 2. Wilson 区间必须与桶内计数自洽
stats = summ.get("stats", {})
buckets = {b["bucket"]: b for b in stats.get("buckets", [])}
bad_w = []
for name, bucket_rows in (("third-party", third), ("lgd", lgd)):
    b = buckets.get(name)
    if not b:
        bad_w.append("%s: no bucket" % name)
        continue
    n, passed = len(bucket_rows), sum(1 for r in bucket_rows if r["score"] >= b["pass_bar"])
    lo, hi = b["wilson95"]
    if b["n"] != n:
        bad_w.append("%s n %s≠%s" % (name, b["n"], n))
    if b["passed"] != passed:
        bad_w.append("%s passed %s≠%s" % (name, b["passed"], passed))
    if abs(b["share"] - (passed / n if n else 0)) > 5e-4:
        bad_w.append("%s share %s≠%s" % (name, b["share"], passed / n if n else 0))
    if not (0 <= lo <= b["share"] <= hi <= 1):
        bad_w.append("%s interval [%s,%s] excludes share %s" % (name, lo, hi, b["share"]))
case("leaderboard: Wilson buckets recompute from rows", not bad_w, str(bad_w) or "third-party and lgd buckets all self-consistent")

# 3. run-proof 与 leaderboard 的 LGD 集合必须同一批包
proof_pkgs = {p["package"]: p for p in rp["packages"]}
case("run-proof: package set equals leaderboard lgd set",
     set(proof_pkgs) == {r["target"] for r in lgd},
     "proof=%s lgd=%s" % (sorted(proof_pkgs), sorted(r["target"] for r in lgd)))
dim_bad = []
for name, p in proof_pkgs.items():
    if sum(p["dimensions"].values()) != p["score"]:
        dim_bad.append("%s dims %s≠score %s" % (name, sum(p["dimensions"].values()), p["score"]))
    if p["verdict"] != "PASS" or not p.get("tests_executed"):
        dim_bad.append("%s verdict/tests_executed" % name)
case("run-proof: score equals sum of dimensions and tests really ran", not dim_bad, str(dim_bad) or "all packages")

# 4. drift-check 的 result 必须能从 rows 重算
dc_rows = dc["rows"]
drifted = [r for r in dc_rows if r["drift"] != 0]
bad_d = []
if dc["result"]["checked"] != len(dc_rows):
    bad_d.append("checked %s≠%s" % (dc["result"]["checked"], len(dc_rows)))
if dc["result"]["drifted"] != len(drifted):
    bad_d.append("drifted %s≠%s" % (dc["result"]["drifted"], len(drifted)))
mx = max((abs(r["drift"]) for r in dc_rows), default=0)
if dc["result"]["max_abs_drift"] != mx:
    bad_d.append("max_abs_drift %s≠%s" % (dc["result"]["max_abs_drift"], mx))
bad_d += ["%s: drift %s≠new-old %s" % (r["target"], r["drift"], r["new"] - r["old"])
          for r in dc_rows if r["drift"] != r["new"] - r["old"]]
case("drift-check: headline result recomputes from rows", not bad_d, str(bad_d) or "checked/drifted/max all recomputed")

# 5. 漂移复核的样本必须覆盖 leaderboard 里的全部第三方目标
lb_targets = {r["target"] for r in third}
dc_targets = {r["target"] for r in dc_rows}
case("drift-check: covers exactly the third-party sample",
     dc_targets == lb_targets,
     "only-in-drift=%s only-in-leaderboard=%s"
     % (sorted(dc_targets - lb_targets), sorted(lb_targets - dc_targets)))

# 6. landscape：每个项目可溯源（https 链接 + 唯一 repo）；
#    引用版本的项目必须同时给发布日期（"release" 与 "released" 不能只有一半）
projects = ls["projects"]
missing = [p.get("repo") for p in projects if not str(p.get("url", "")).startswith("https://") or not p.get("repo")]
half_version = [p["repo"] for p in projects if bool(p.get("release")) != bool(p.get("released"))]
dupes = len({p["repo"] for p in projects}) != len(projects)
case("landscape: every project has a traceable https source",
     not missing and not dupes and not half_version,
     "bad=%s half_version=%s duplicated=%s" % (missing, half_version, dupes))

# 7. rubric：权重和必须为 100，且每个维度的 declared 分必须等于它的权重。
#    注意不能要求"checks 分数之和 == declared"：consistency 维含一条"替代路径，与前两项互斥"
#    判据（10+5+5+5=25 是主路径，另一条 5 分与前两项互斥），互斥判据的分数之和天然会大于
#    该维上限。用 run-proof 的实际维度分 ≤ 权重来验证上限真的生效。
w_sum = sum(d["weight"] for d in rb["dimensions"])
decl_bad = [d["key"] for d in rb["dimensions"] if d["points_declared"] != d["weight"]]
weights = {d["key"]: d["weight"] for d in rb["dimensions"]}
over_cap = ["%s %s>%s" % (name, v, weights[k])
            for name, p in proof_pkgs.items() for k, v in p["dimensions"].items()
            if k in weights and v > weights[k]]
case("rubric: weights sum to 100, each dimension declares its own weight, no score exceeds its cap",
     w_sum == 100 and not decl_bad and not over_cap,
     "weights=%d bad_dims=%s over_cap=%s" % (w_sum, decl_bad, over_cap))

# 8. 上限口径：静态上限 + run 加分 == 总分上限
case("rubric: static cap plus run credit equals the full scale",
     rb["scale"]["max_static"] + 4 == rb["scale"]["max_with_run"],
     "%s + 4 = %s" % (rb["scale"]["max_static"], rb["scale"]["max_with_run"]))

ok = sum(1 for c in results if c)
print("\nENDPOINT-CONSISTENCY: %d/%d" % (ok, len(results)))
sys.exit(0 if ok == len(results) else 1)
